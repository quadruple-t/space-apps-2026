def b64(arr: np.ndarray | bytes) -> dict:
    """Encode a numpy array (forced little-endian) or raw bytes as a seed Bytes field."""
    if isinstance(arr, np.ndarray):
        a = arr
        if a.dtype.byteorder == ">" or (a.dtype.byteorder == "=" and sys.byteorder == "big"):
            a = a.byteswap().view(a.dtype.newbyteorder("<"))
        raw = np.ascontiguousarray(a).tobytes()
    else:
        raw = arr
    return {"$bytes": base64.b64encode(raw).decode("ascii")}


def write_doc(collection: str, doc_id: str, data: dict) -> Path:
    """Write data/seed/<collection>/<doc_id>.json. Sub-collections use a path like
    "sites/apollo-11-tranquility/terrain" for collection."""
    out = SEED / collection / f"{doc_id}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as f:
        json.dump(data, f, indent=1, ensure_ascii=False, allow_nan=False)
        f.write("\n")
    return out


def clear_collection(collection: str) -> None:
    d = SEED / collection
    if d.exists():
        for p in d.glob("*.json"):
            p.unlink()


def read_json(path: Path | str) -> Any:
    with open(path) as f:
        return json.load(f)


def curated(name: str) -> Any:
    return read_json(CURATED / name)


def finite_or_none(x: Any, nd: int | None = None) -> float | None:
    if x is None:
        return None
    x = float(x)
    if not np.isfinite(x):
        return None
    return round(x, nd) if nd is not None else x


