@contextlib.contextmanager
def _manifest_lock():
    """Serialise manifest read-modify-write across concurrent fetch processes."""
    with open(PIPELINE_DIR / ".manifest.lock", "w") as lf:
        fcntl.flock(lf, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lf, fcntl.LOCK_UN)


def _load_manifest() -> dict:
    if MANIFEST.exists():
        return read_json(MANIFEST)
    return {"_note": "Every file the pipeline downloaded or range-read. Regenerated by 00_fetch.py.", "files": {}, "rangeReadSources": {}}


def _save_manifest(m: dict) -> None:
    m["files"] = dict(sorted(m["files"].items()))
    m["rangeReadSources"] = dict(sorted(m.get("rangeReadSources", {}).items()))
    tmp = MANIFEST.with_suffix(f".tmp{os.getpid()}")
    with open(tmp, "w") as f:
        json.dump(m, f, indent=1)
        f.write("\n")
    os.replace(tmp, MANIFEST)  # atomic: concurrent readers never see a partial file


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(8 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _accepts_ranges(head: requests.Response) -> bool:
    return head.headers.get("Accept-Ranges", "").lower() == "bytes" or "pds-geosciences" in head.url


def _segmented_fetch(url: str, part: Path, start: int, total: int, headers: dict, rel: str, nseg: int) -> None:
    from concurrent.futures import ThreadPoolExecutor

    bounds = [start + (total - start) * i // nseg for i in range(nseg + 1)]
    segs = [part.with_suffix(part.suffix + f".seg{i}of{nseg}") for i in range(nseg)]
    progress = [0] * nseg
    t0 = time.time()

    def fetch(i: int) -> None:
        lo, hi = bounds[i], bounds[i + 1]  # [lo, hi)
        for attempt in range(8):
            have = segs[i].stat().st_size if segs[i].exists() else 0
            progress[i] = have
            if have >= hi - lo:
                return
            try:
                h = dict(headers, Range=f"bytes={lo + have}-{hi - 1}")
                with requests.get(url, stream=True, timeout=120, headers=h, allow_redirects=True) as r:
                    if r.status_code != 206:
                        raise RuntimeError(f"expected 206, got {r.status_code}")
                    with open(segs[i], "ab") as f:
                        for chunk in r.iter_content(1 << 20):
                            f.write(chunk)
                            progress[i] += len(chunk)
            except Exception as e:
                log(f"  {rel} seg {i}: retry {attempt + 1}: {e}")
                time.sleep(5 * (attempt + 1))
        if segs[i].stat().st_size != hi - lo:
            raise RuntimeError(f"segment {i} of {rel} incomplete")

    with ThreadPoolExecutor(nseg) as ex:
        futs = [ex.submit(fetch, i) for i in range(nseg)]
        while not all(f.done() for f in futs):
            time.sleep(15)
            done = sum(progress)
            log(f"  {rel}: {(start + done)/1e6:,.0f}/{total/1e6:,.0f} MB ({done/max(1e-6, time.time()-t0)/1e6:.2f} MB/s, {nseg} ranges)")
        for f in futs:
            f.result()
    with open(part, "ab") as out:
        for s in segs:
            with open(s, "rb") as f:
                while chunk := f.read(8 << 20):
                    out.write(chunk)
    for s in segs:
        s.unlink()


def download(url: str, rel: str | None = None, *, retries: int = 5) -> Path:
    """Download a whole file into .cache/ (resumable, idempotent) and record it in the manifest."""
    rel = rel or url.split("/")[-1]
    dest = CACHE / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    with _manifest_lock():
        entry = _load_manifest()["files"].get(rel)
    if dest.exists() and entry and entry.get("bytes") == dest.stat().st_size and entry.get("sha256"):
        return dest

    headers = {"User-Agent": USER_AGENT}
    head = requests.head(url, allow_redirects=True, timeout=60, headers=headers)
    head.raise_for_status()
    total = int(head.headers.get("Content-Length", 0))
    last_mod = head.headers.get("Last-Modified")
    etag = head.headers.get("ETag")

    if dest.exists() and (not total or dest.stat().st_size == total):
        # Complete file without a manifest entry (e.g. interrupted bookkeeping): record it.
        digest = sha256_file(dest)
        with _manifest_lock():
            m = _load_manifest()
            m["files"][rel] = {"url": url, "bytes": dest.stat().st_size, "sha256": digest,
                               "lastModified": last_mod, "etag": etag, "retrievedAt": now_iso()}
            _save_manifest(m)
        return dest

    part = dest.with_suffix(dest.suffix + ".part")
    # Large files: fetch the remainder as parallel byte ranges (the slow servers we use are
    # per-connection limited). Segments resume independently, then are appended to .part.
    have0 = part.stat().st_size if part.exists() else 0
    if total > 150e6 and total - have0 > 50e6 and _accepts_ranges(head):
        _segmented_fetch(url, part, have0, total, headers, rel, nseg=4)
    for attempt in range(retries):
        try:
            have = part.stat().st_size if part.exists() else 0
            if total and have >= total:
                break
            h = dict(headers)
            if have:
                h["Range"] = f"bytes={have}-"
            with requests.get(url, stream=True, timeout=120, headers=h, allow_redirects=True) as r:
                if have and r.status_code != 206:
                    have = 0  # server ignored Range; restart
                    mode = "wb"
                else:
                    mode = "ab" if have else "wb"
                r.raise_for_status()
                done, t0, last = have, time.time(), 0.0
                with open(part, mode) as f:
                    for chunk in r.iter_content(1 << 20):
                        f.write(chunk)
                        done += len(chunk)
                        if time.time() - last > 15:
                            last = time.time()
                            rate = (done - have) / max(1e-6, last - t0) / 1e6
                            log(f"  {rel}: {done/1e6:,.0f}/{total/1e6:,.0f} MB ({rate:.1f} MB/s)")
            break
        except Exception as e:  # network hiccup: back off and resume
            log(f"  retry {attempt+1}/{retries} for {rel}: {e}")
            time.sleep(5 * (attempt + 1))
    else:
        raise RuntimeError(f"download failed: {url}")

    if total and part.stat().st_size != total:
        raise RuntimeError(f"size mismatch for {url}: {part.stat().st_size} != {total}")
    part.rename(dest)
    digest = sha256_file(dest)
    with _manifest_lock():
        m = _load_manifest()
        m["files"][rel] = {
            "url": url,
            "bytes": dest.stat().st_size,
            "sha256": digest,
            "lastModified": last_mod,
            "etag": etag,
            "retrievedAt": now_iso(),
        }
        _save_manifest(m)
    log(f"  done {rel} ({dest.stat().st_size/1e6:,.1f} MB)")
    return dest


def record_range_source(key: str, url: str, note: str) -> None:
    """Record a COG / raw-tile source that is range-read rather than downloaded."""
    with _manifest_lock():
        m = _load_manifest()
        m.setdefault("rangeReadSources", {})
        prev = m["rangeReadSources"].get(key, {})
        m["rangeReadSources"][key] = {"url": url, "note": note, "firstReadAt": prev.get("firstReadAt", now_iso())}
        _save_manifest(m)


def cached(rel: str) -> Path:
    p = CACHE / rel
    if not p.exists():
        raise FileNotFoundError(f"{rel} missing from .cache/ - run 00_fetch.py first")
    return p


def manifest_entry(rel: str) -> dict | None:
    with _manifest_lock():
        return _load_manifest()["files"].get(rel)


