"""Shared paths, JSON output helpers, download + manifest bookkeeping.

All stages import from here. Nothing in this module talks to Firestore; stages
write Firestore-ready JSON under data/seed/<collection>/<docId>.json and the
TypeScript seed script (scripts/seed-firestore.ts) uploads it.

Binary fields are written as {"$bytes": "<base64>"} (little-endian payloads);
the seed script converts them to Buffers, which the Admin SDK stores as the
Firestore Bytes type.
"""
