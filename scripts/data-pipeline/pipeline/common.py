RESEARCH_DATE = "2026-11-14"
_REFS: dict | None = None


def ref(key: str, **extra: Any) -> dict:
    """Expand a refs.json key into a SourceRef {label, url, retrievedAt, tier?, note?}."""
    global _REFS
    if _REFS is None:
        _REFS = {k: v for k, v in curated("refs.json").items() if not k.startswith("_")}
    if key not in _REFS:
        raise KeyError(f"unknown source ref '{key}' (add it to curated/refs.json)")
    r = dict(_REFS[key])
    out = {"label": r["label"], "url": r.get("url"), "retrievedAt": r.get("retrievedAt", RESEARCH_DATE)}
    if r.get("tier"):
        out["tier"] = r["tier"]
    note = extra.get("note") or r.get("note")
    if note:
        out["note"] = note
    return out


def refs(keys: list[str]) -> list[dict]:
    return [ref(k) for k in keys]
