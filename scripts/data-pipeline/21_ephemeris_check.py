#!/usr/bin/env python3
"""Stage 21: validate the client topocentric math against direct Horizons quantity 4.

5 sites x 30 epochs (2027-03-01 00:30 .. 2027-03-30 00:30 UTC, daily, deliberately at :30 so the
stored hourly series must be interpolated). For each epoch we keep the exact Horizons sub-point
inputs and the direct topocentric az/el for Sun and Earth. Two comparisons:
  (a) client math on the exact sub-points        (tests lib/ephemeris/topocentric.ts)
  (b) client math on the stored 1 h series, lerped (tests decode + series + topocentric)
Writes data/seed/fixtures/topocentric-check.json (read by vitest) and
data/seed/_reports/ephemeris-check.json (numbers for docs/METHODS.md). Fails if any |error| > 0.02°.
Reuses the method of docs/research/horizons-spot-check/compare.py.
"""
import datetime as dt
import json
import sys

import numpy as np

from pipeline.common import SEED, now_iso, write_doc
from pipeline.ephem import Series, azel_from_cart
from pipeline.geo import topo_azel
from pipeline.horizons import COMMON, parse_time, query, table

TOL = 0.02
SITES = [
    ("Apollo 11 (LROC)", 0.67416, 23.47314),
    ("Shackleton rim", -89.45, -137.31),
    ("S-pole -84.8/33.0", -84.8, 33.0),
    ("Chandrayaan-3 (LROC)", -69.374, 32.3187),
    ("Chang'e-4 (LROC)", -45.4561, 177.5885),
]
SPAN = {"START_TIME": "'2027-03-01 00:30'", "STOP_TIME": "'2027-03-30 00:30'", "STEP_SIZE": "'1 d'"}


def angdiff(a, b):
    return (np.asarray(a) - np.asarray(b) + 180.0) % 360.0 - 180.0


def main():
    d, sp_url = query({**COMMON, **SPAN, "COMMAND": "'301'", "CENTER": "'500@399'", "QUANTITIES": "'14,15,19,20'"}, "check-subpts")
    hdr, rows = table(d)
    ix = {h: i for i, h in enumerate(hdr)}
    epochs = [parse_time(r[0]) for r in rows]
    sub = np.array([[float(r[ix[c]]) for c in ["SunSub-LAT", "SunSub-LON", "r", "ObsSub-LAT", "ObsSub-LON", "delta"]] for r in rows])
    series = Series(["2027-02", "2027-03", "2027-04"])
    tms = [dt.datetime.fromisoformat(e.replace("Z", "+00:00")) for e in epochs]
    sun_c = np.vstack([series.at(t)[0] for t in tms])
    earth_c = np.vstack([series.at(t)[1] for t in tms])

    fixture = {"_note": "Generated by scripts/data-pipeline/21_ephemeris_check.py. Horizons direct quantity-4 az/el vs sub-point inputs.",
               "generatedAt": now_iso(), "toleranceDeg": TOL, "subpointQuery": sp_url,
               "layout": ["sunLatDeg", "sunLonDeg", "sunDistKm", "earthLatDeg", "earthLonDeg", "earthDistKm"],
               "epochs": epochs, "subpoints": sub.tolist(), "seriesChunkIds": ["2027-02", "2027-03", "2027-04"], "sites": []}
    report = {"generatedAt": now_iso(), "toleranceDeg": TOL, "nEpochs": len(epochs), "rows": []}
    worst = 0.0
    for name, lat, lon in SITES:
        site = {"name": name, "latDeg": lat, "lonDeg": lon}
        for body, tgt, sl, slon, sdist, cart in [("sun", "10", 0, 1, 2, sun_c), ("earth", "399", 3, 4, 5, earth_c)]:
            dd, url = query({**COMMON, **SPAN, "COMMAND": f"'{tgt}'", "CENTER": "'coord@301'", "COORD_TYPE": "'GEODETIC'",
                             "SITE_COORD": f"'{lon},{lat},0'", "QUANTITIES": "'4'"}, "check-topo")
            h2, r2 = table(dd)
            assert [parse_time(r[0]) for r in r2] == epochs
            hz = np.array([[float(r[3]), float(r[4])] for r in r2])
            az_a, el_a = topo_azel(lat, lon, sub[:, sl], sub[:, slon], sub[:, sdist])
            az_b, el_b = azel_from_cart(lat, lon, cart)
            cos_el = np.cos(np.radians(hz[:, 1]))
            stats = {}
            for tag, az, el in [("exact", az_a, el_a), ("interpolated", az_b, el_b)]:
                daz = np.abs(angdiff(az, hz[:, 0]))
                dazc = daz * cos_el
                de = np.abs(el - hz[:, 1])
                stats[tag] = {"maxAbsDEl": float(de.max()), "meanAbsDEl": float(de.mean()),
                              "maxAbsDAz": float(daz.max()), "maxAbsDAzCosEl": float(dazc.max())}
                worst = max(worst, float(de.max()), float(dazc.max()))
            site[body] = {"horizonsQuery": url, "azEl": hz.tolist()}
            report["rows"].append({"site": name, "body": body, **stats})
        fixture["sites"].append(site)

    (SEED / "fixtures").mkdir(parents=True, exist_ok=True)
    with open(SEED / "fixtures/topocentric-check.json", "w") as f:
        json.dump(fixture, f, indent=1)
    report["worstDeg"] = worst
    report["pass"] = worst <= TOL
    with open(SEED / "_reports/ephemeris-check.json", "w") as f:
        json.dump(report, f, indent=1)
    for r in report["rows"]:
        print(f"{r['body']:5s} {r['site']:22s} exact dEl {r['exact']['maxAbsDEl']:.5f} dAz·cos {r['exact']['maxAbsDAzCosEl']:.5f} | "
              f"interp dEl {r['interpolated']['maxAbsDEl']:.5f} dAz·cos {r['interpolated']['maxAbsDAzCosEl']:.5f}")
    print(f"worst {worst:.5f}° (tolerance {TOL}°) -> {'PASS' if worst <= TOL else 'FAIL'}")
    if worst > TOL:
        sys.exit(1)


if __name__ == "__main__":
    main()
